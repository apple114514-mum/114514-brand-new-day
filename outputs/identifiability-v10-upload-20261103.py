# ---------------------------------------------------------------- 日志工具
def dw(s):
    """CJK 全角计 2，其余计 1。"""
    return sum(2 if unicodedata.east_asian_width(c) in 'WF' else 1 for c in s)


def pad(s, w, right=False):
    s = str(s)
    n = w - dw(s)
    if n <= 0:
        return s
    return (' ' * n + s) if right else (s + ' ' * n)


def L(s=''):
    print(s)
    LOG.append(s)


def row(cells, widths, right=()):
    return '  ' + ' '.join(pad(c, w, i in right) for i, (c, w) in enumerate(zip(cells, widths)))


def pct(x, nd=4):
    return ('%+.' + str(nd) + 'f%%') % (100.0 * x)


# ---------------------------------------------------------------- 案例
# Zhao 2020 成对 CFD：d=0.5、lambda=0.5、H_R=2、Q_R=10/1.767767 MW、n=1/4
Z = V.Model(0.5, 0.5, 2.0, V.QR_ZHAO, 0.25)

W0 = 0.291472160          # 第八轮由 K_R 反解（delta=0 标定）
X0 = Z.solve_s(W0)        # 自洽解 x = r_m/R_id
F0 = Z.f_s(X0)
M0 = Z.M_s(X0)
KR = X0 ** 3 / M0         # = G(x_R, w_R) = (1-w) + w f
D0 = X0 - 1.0

XT = 1.03                 # 3% 判据端点
KT = XT ** 3 / Z.M_s(XT)
FT = Z.f_s(XT)


def x_of(A, B, d=0.5, lam=0.5, delta=0.0):
    """给定聚合量 (A,B)，解 F=0。A 与 B 与 (w, delta, c) 的具体分解无关。"""
    m = V.Model(d, lam, 2.0, V.QR_ZHAO, 0.25, delta=delta)

    def F(x):
        return x ** 3 * (m._rho_s(m.T_s(x)) / m._rho_s(m.T_P)) - \
            (A + B * m.f_s(x)) * (m._cp_s(m.T_s(x)) / m._cp_s(m.T_P))

    lo, hi = 0.05, 6.0
    flo = F(lo)
    for _ in range(400):
        mid = 0.5 * (lo + hi)
        if mid <= lo or mid >= hi:
            break
        if (flo < 0) == (F(mid) < 0):
            lo, flo = mid, F(mid)
        else:
            hi = mid
    return 0.5 * (lo + hi)


