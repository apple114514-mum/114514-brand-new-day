def itp(tab, m, icol):
    xs = [t[0] for t in tab]
    ks = [t[icol] for t in tab]
    if m <= xs[0]:
        return ks[0] + (ks[1] - ks[0]) / (xs[1] - xs[0]) * (m - xs[0])
    for i in range(len(xs) - 1):
        if m <= xs[i + 1]:
            t = (m - xs[i]) / (xs[i + 1] - xs[i])
            return ks[i] + t * (ks[i + 1] - ks[i])
    return ks[-1]


