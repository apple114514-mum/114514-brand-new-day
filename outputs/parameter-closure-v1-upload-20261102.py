KYLIN_LOW = dict(Re_R=1.0 - 0.12151, c=0.5, lR=0.5, dR=1.0)         # 降高度，D_m=-12.151%
KYLIN_K_TOT = 11.593          # 由 24 kW / 1.2 kg/s 单点标定（loop_audit_repair.py）
KYLIN_L = 12.0
KYLIN_D = 0.026
KYLIN_M = 1.2

