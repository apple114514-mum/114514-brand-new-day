"""参数溯源表的闭合：把 delta 从「待测数据」改为「由 Re 比给出的包络」
--------------------------------------------------------------------------
背景：卡了一个月的不是整张表，是其中一行——原型与台架的逐段局部阻力
（K_EV / K_HS / K_pipe，两侧各一套），因为它只以组合量
    delta = k_M/k_P - 1
进入 FoM，而任何单侧资料都只能定 w、不能定 delta。

本脚本做四件事：
  [A] 定义「有来源」的四个等级，避免把推导值当直读值
  [B] 给出 delta 的物理包络（不依赖任何图纸）：0 <= delta <= Re_R^(-m) - 1
  [C] 由包络反解设计规则：要 Re_R 多大才由相似性保证 |D|<=3%
  [D] 把 US（热损）从自由参数变成可算量：保温层热平衡
  [E] 逐项溯源表（值 / 等级 / 区间 / 还缺什么）

运行：python provenance_closure_v1.py
"""
