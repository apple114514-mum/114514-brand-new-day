# ================================================================ B
def sec_B():
    L('')
    L('=' * 78)
    L('[B] delta 的物理包络：不需要任何图纸')
    L('=' * 78)
    L('  假设 A1：两回路同为湍流、构件类型与数量相同（几何相似构件）。')
    L('  假设 A2：单个构件的局部损失系数 K_i(Re) 随 Re 单调不增，且其 Re 指数')
    L('           不超过壁面摩擦的 0.2（分离损失比壁面摩擦对 Re 更不敏感，')
    L('           故 f 的标度是局部损失 Re 依赖的**上包络**）。')
    L('  在 A1+A2 下：')
    L('      K_i^M / K_i^P <= (Re_M / Re_P)^(-0.2) = Re_R^(-0.2)')
    L('      对求和仍成立 => 1 <= k_M/k_P <= Re_R^(-0.2)')
    L('      即  0 <= delta <= Re_R^(-0.2) - 1')
    L('  下界取 0 不需要 A2，只需 K 不随 Re 增大而增大（A2 的更弱形式）。')
    L('')
    L('  数值（Re 指数取 0.2，另给 0.3 作敏感性）：')
    W = [26, 10, 18, 18]
    L(row(['案例', 'Re_R', 'delta_hi (m=.2)', 'delta_hi (m=.3)'], W, (1, 2, 3)))
    L('  ' + '-' * 76)
    for name, c in (('赵 2020 成对 CFD', ZHAO),
                    ('KYLIN-II 全相似 l_R=.5', KYLIN_FULL),
                    ('KYLIN-II 降高度', KYLIN_LOW)):
        R = c['Re_R']
        L(row([name, '%.4f' % R,
               '%.4f' % (100 * (R ** -0.2 - 1)),
               '%.4f' % (100 * (R ** -0.3 - 1))], W, (1, 2, 3)))
    L('')
    L('  => 包络上端在 m=0.2 下是 2.62% / 18.11% / 23.64%，不是「±7%」也不是「未知」；')
    L('     指数取 0.3 则放大到 3.96% / 28.36% / 37.48%。这条界只对 delta>0 一侧有内容：')
    L('     delta<0 需要「台架构件比原型更少或更顺」的额外事实，本包络不给。')

# ================================================================ C
def sec_C():
    L('')
    L('=' * 78)
    L('[C] 反解设计规则：相似性本身能把 |D| 压在 3% 以内吗')
    L('=' * 78)
    # delta_crit = K_+ - 1，用模型自算，不抄数
    z = V.Model(0.5, 0.5, 2.0, V.QR_ZHAO, 0.25, delta=0.0)
    def Kt(x): return x ** 3 / z.M_s(x)
    dcrit = Kt(1.03) - 1.0
    L('  Zhao 本体（c=1, delta=0）的 3%% 正向上限 delta_crit = K_+ - 1 = %.9f' % dcrit)
    L('  令包络上端 <= delta_crit：  Re_R^(-m) - 1 <= dcrit  <=>  Re_R >= (1+dcrit)^(-1/m)')
    L('')
    L('  %-10s %-18s %-18s' % ('Re 指数 m', '所需最小 Re_R', '含义'))
    L('  ' + '-' * 60)
    for m in (0.15, 0.2, 0.3):
        need = (1.0 + dcrit) ** (-1.0 / m)
        L(row(['%.2f' % m, '%.4f' % need, '低于此值，相似性无法保证 3%'],
              [8, 16, 34], (1,)))
    L('')
    L('  对照三个案例的 Re_R：')
    need2 = (1.0 + dcrit) ** (-1.0 / 0.2)
    for name, c in (('赵 2020', ZHAO), ('KYLIN 全相似', KYLIN_FULL), ('KYLIN 降高度', KYLIN_LOW)):
        R = c['Re_R']
        L('    %s Re_R=%.4f  %s'
          % (pad(name, 16), R,
             '达标' if R >= need2 else '不达标（缺口 %.0f%%）' % (100 * (need2 / R - 1))))
    L('')
    L('  => 这是本轮最该写进论文的一句：')
    L('     「几何相似 + 充分湍流」并不能自动保证 3%%，它只在 Re_R >= %.2f 时保证。' % need2)
    L('     赵的 Re_R=0.346、KYLIN 全相似的 0.435 都在门外，')
    L('     所以二者的 3% 是**观测到的**（2.88%），不是**由相似性推出的**。')
    L('     降高度那一条 Re_R=0.879 反而达标 —— 它的 -12% 不来自 delta，')
    L('     而来自「局部损失不随长度缩、摩擦项却按 lambda/d 缩」，两者是不同机制。')
    L('     这不是坏消息：它把「delta 未知」换成了「Re_R 必须多大」，是设计要求，不是数据缺口。')
    L('')
    L('  把包络上端代回 3% 带，看带是否还对任何 w 非空：')
    ft = z.f_s(1.03)
    L('    K_+ = %.9f   f_+ = %.9f   delta_crit = %.9f' % (Kt(1.03), ft, dcrit))
    W2 = [26, 16, 16, 20]
    L(row(['Re_R', 'delta 包络上端', 'w_+(该 delta)', '3% 带'], W2, (1, 2, 3)))
    L('  ' + '-' * 78)
    for name, c in (('赵 2020', ZHAO), ('KYLIN 全相似', KYLIN_FULL), ('KYLIN 降高度', KYLIN_LOW)):
        R = c['Re_R']
        dh = R ** -0.2 - 1.0
        A = 1.0 + dh
        wp = (Kt(1.03) - A) / (ft - A)
        L(row([name + ' (%.4f)' % R, '%.4f' % dh, '%.4f' % wp,
               '非空' if wp > 0 else '空'], W2, (1, 2, 3)))
    L('')
    L('  => 赵与 KYLIN 全相似在包络上端 w_+ 为负，3% 带整段消失；')
    L('     只有降高度那一条（Re_R=.879）在包络内仍留有可行 w。')
    L('     这就是「相似性保证不了 3%」的定量形态，不是一句定性担心。')

