def sec_D():
    L('')
    L('=' * 78)
    L('[D] US（热损）不是自由参数：保温层热平衡给区间')
    L('=' * 78)
    Tamb = 298.15
    Tb = 600.0
    dT = Tb - Tamb
    r1 = KYLIN_D / 2.0
    L('  基准：管内 600 K、环境 298 K、管长 %.0f m、内径 %.0f mm' % (KYLIN_L, 1000 * KYLIN_D))
    WD = [14, 12, 12, 12, 12]
    L(row(['保温厚度', '外径 mm', "R' K.m/W", 'Q_loss W', 'US W/K'], WD, (1, 2, 3, 4)))
    L('  ' + '-' * 70)
    rows = []
    for t_ins, k_ins in ((0.0, None), (0.02, 0.045), (0.04, 0.045), (0.06, 0.045)):
        r2 = r1 + t_ins
        if t_ins > 0:
            Rc = math.log(r2 / r1) / (2 * math.pi * k_ins)
        else:
            Rc = 0.0
        h_out = 10.0
        Rv = 1.0 / (h_out * 2 * math.pi * r2)
        Rtot = Rc + Rv
        q = dT / Rtot * KYLIN_L
        us = q / dT
        rows.append((t_ins, r2, Rtot, q, us))
        L(row(['%.0f mm' % (1000 * t_ins) if t_ins else '裸管',
               '%.1f' % (1000 * 2 * r2), '%.3f' % Rtot,
               '%.0f' % q, '%.2f' % us], WD, (1, 2, 3, 4)))
    L('')
    L('  => 裸管 9.8 W/K、20 mm 保温 3.2、40 mm 2.3、60 mm 1.9。')
    L('     现有模型标定用的是 US=6 W/K —— 落在「薄保温」那一档，但它是**选出来的**，不是算出来的。')
    L('     按「由关联式算」的等级，应改报 US = 1.9 ~ 3.2 W/K（有保温），把 6 W/K 降级为 L4 情景值。')
    L('     影响：US 只进 epsilon_Q 这一笔口径账，不进 delta；单点标定下')
    L('     US 6->0 使 k_tot 变 15% 而 m 只变 0.85%（前面已核），所以这条改动是 0.1 pp 量级。')

