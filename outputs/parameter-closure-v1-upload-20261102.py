def dw(s):
    """显示宽度：CJK 记 2，其余记 1。用于把中英混排的表格对齐。"""
    return sum(2 if unicodedata.east_asian_width(ch) in 'WF' else 1 for ch in str(s))

def pad(s, n, right=False):
    s = str(s)
    k = n - dw(s)
    if k <= 0:
        return s
    return (' ' * k + s) if right else (s + ' ' * k)

def row(cells, widths, rights=()):
    out = []
    for i, c in enumerate(cells):
        out.append(pad(c, widths[i], i in rights))
    return '  ' + ' '.join(out)

# ---------------------------------------------------------------- 物性（杨若楠 2020 表 2）
def rho(T): return 11096.0 - 1.3236 * T
def mu(T):  return 4.94e-4 * math.exp(754.1 / T)
def cp(T):  return 159.0 - 0.0272 * T + 7.12e-6 * T * T
def lam(T): return 3.61 + 0.01517 * T - 1.741e-6 * T * T

G = 9.80665

def blake(Re): return 0.3164 * Re ** (-0.25)

# ---------------------------------------------------------------- 已知锚（全部已核）
ZHAO = dict(Re_R=0.3461, c=1.0, lR=0.5, dR=0.5)
