def map1(rm=RM, d=0.5, HR=2.0, QR=QR_Z):
    # 显式 d 的闭式；A_R 在此与 d 绑定（A_R = 1/d^2）
    return rm * d ** (4.0 / 3.0) / (HR * QR) ** (1.0 / 3.0) - 1.0


def map1_AR(rm=RM, AR=4.0, HR=2.0, QR=QR_Z):
    # 松懈版：A_R 独立于 d（承认 net flow area 不必等于 1/d^2）
    Rid = (AR * AR * HR * QR) ** (1.0 / 3.0)
    return rm / Rid - 1.0


def map2(d=0.5, lam=0.5, HR=2.0, QR=QR_Z, n=0.25):
    return V.Model(d, lam, HR, QR, n).solve_s(W0) - 1.0


